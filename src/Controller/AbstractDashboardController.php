<?php

namespace EasyCorp\Bundle\EasyAdminBundle\Controller;

use EasyCorp\Bundle\EasyAdminBundle\Config\Action;
use EasyCorp\Bundle\EasyAdminBundle\Config\Actions;
use EasyCorp\Bundle\EasyAdminBundle\Config\Assets;
use EasyCorp\Bundle\EasyAdminBundle\Config\Crud;
use EasyCorp\Bundle\EasyAdminBundle\Config\Dashboard;
use EasyCorp\Bundle\EasyAdminBundle\Config\Filters;
use EasyCorp\Bundle\EasyAdminBundle\Config\MenuItem;
use EasyCorp\Bundle\EasyAdminBundle\Config\UserMenu;
use EasyCorp\Bundle\EasyAdminBundle\Contracts\Controller\DashboardControllerInterface;
use EasyCorp\Bundle\EasyAdminBundle\Contracts\Provider\AdminContextProviderInterface;
use EasyCorp\Bundle\EasyAdminBundle\Contracts\Widget\WidgetInterface;
use EasyCorp\Bundle\EasyAdminBundle\Factory\WidgetFactory;
use EasyCorp\Bundle\EasyAdminBundle\Router\AdminUrlGenerator;
use EasyCorp\Bundle\EasyAdminBundle\Router\AdminUrlGeneratorInterface;
use EasyCorp\Bundle\EasyAdminBundle\Security\Permission;
use EasyCorp\Bundle\EasyAdminBundle\Widget\WidgetRenderer;
use EasyCorp\Bundle\EasyAdminBundle\Widget\WidgetSection;
use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\HttpException;
use Symfony\Component\Security\Core\User\UserInterface;
use Symfony\Component\Security\Http\Attribute\IsGranted;
use function Symfony\Component\Translation\t;

/**
 * This class is useful to extend your dashboard from it instead of implementing
 * the interface.
 *
 * @author Javier Eguiluz <javier.eguiluz@gmail.com>
 */
abstract class AbstractDashboardController extends AbstractController implements DashboardControllerInterface
{
    public static function getSubscribedServices(): array
    {
        return array_merge(parent::getSubscribedServices(), [
            AdminUrlGeneratorInterface::class => '?'.AdminUrlGeneratorInterface::class,
            // the following key is kept for BC reasons
            AdminUrlGenerator::class => '?'.AdminUrlGeneratorInterface::class,
            AdminContextProviderInterface::class => '?'.AdminContextProviderInterface::class,
            WidgetFactory::class => '?'.WidgetFactory::class,
            WidgetRenderer::class => '?'.WidgetRenderer::class,
        ]);
    }

    public function index(): Response
    {
        // dashboards that don't define widgets display a welcome page with instructions for developers;
        // dashboards that define them never display it, even if the current user can't see any widget
        $definesWidgets = self::class !== (new \ReflectionMethod($this, 'configureWidgets'))->getDeclaringClass()->getName();
        $adminContext = $this->container->has(AdminContextProviderInterface::class) ? $this->container->get(AdminContextProviderInterface::class)->getContext() : null;

        if (!$definesWidgets) {
            return $this->render('@EasyAdmin/welcome.html.twig', [
                'dashboard_controller_filepath' => (new \ReflectionClass(static::class))->getFileName(),
            ]);
        }

        // this happens when the request matched a route not generated by EasyAdmin (e.g. the one of a
        // #[Route] attribute applied to index()); the dashboard page needs the admin context to be rendered
        if (null === $adminContext) {
            throw $this->createNotFoundException(sprintf('The "%s" dashboard can only be displayed through the route defined in its #[AdminDashboard] attribute, but the request matched another route.', static::class));
        }

        return $this->render($adminContext->getTemplatePath('page/dashboard'));
    }

    /**
     * Returns the HTML contents of a single widget. It's used to load the contents
     * of lazy widgets and to reload the widgets that define a refresh interval.
     *
     * This is an action of the dashboard controller (instead of a separate controller)
     * so the #[IsGranted] attributes of the dashboard class also protect the contents
     * of its widgets. The attributes of the index() method are checked below and the
     * 'access_control' rules of the dashboard page are checked by AdminRouterSubscriber.
     */
    public function renderWidget(string $widgetName): Response
    {
        if (!$this->container->has(WidgetFactory::class) || !$this->container->has(WidgetRenderer::class)) {
            throw $this->createNotFoundException();
        }

        $this->denyAccessUnlessIndexIsGranted();

        $widgets = $this->container->get(WidgetFactory::class)->getWidgets();
        if (null === $widget = $widgets->get($widgetName)) {
            if ($widgets->isDenied($widgetName)) {
                throw $this->createAccessDeniedException(sprintf('You don\'t have permission to see the "%s" widget.', $widgetName));
            }

            throw $this->createNotFoundException(sprintf('The "%s" dashboard has no widget called "%s".', static::class, $widgetName));
        }

        // PHP locks the session until the response is sent, so the widgets of a page
        // would load one after another; nothing is written to the session from here on
        $request = $this->container->get('request_stack')->getCurrentRequest();
        if (null !== $request && $request->hasSession() && $request->getSession()->isStarted()) {
            $request->getSession()->save();
        }

        $widgetRenderer = $this->container->get(WidgetRenderer::class);
        $response = new Response($widgetRenderer->renderBody($widget));
        if ($widgetRenderer->hasFailed($widget)) {
            // the error status makes the JavaScript code display its own error message and dispatch the error event
            $response->setStatusCode(Response::HTTP_INTERNAL_SERVER_ERROR);
        }
        $response->headers->set(WidgetRenderer::RESPONSE_HEADER, $widgetName);
        $response->headers->set('X-Robots-Tag', 'noindex');
        // the contents depend on the user and they have their own cache on the server (see the setCache() method of widgets)
        $response->setPrivate();
        $response->headers->addCacheControlDirective('no-store');

        return $response;
    }

    /**
     * Symfony only applies the #[IsGranted] attributes of the class and of the method that
     * runs, so the attributes that protect the index() method must be checked here to
     * protect the widgets the same way as the page that displays them.
     */
    private function denyAccessUnlessIndexIsGranted(): void
    {
        $requestMethod = $this->container->get('request_stack')->getCurrentRequest()?->getMethod() ?? 'GET';

        // like Symfony does, this includes the custom attributes that extend IsGranted
        foreach ((new \ReflectionMethod($this, 'index'))->getAttributes(IsGranted::class, \ReflectionAttribute::IS_INSTANCEOF) as $reflectionAttribute) {
            $isGranted = $reflectionAttribute->newInstance();

            // older Symfony versions don't define the option that restricts the attribute to some HTTP methods
            $httpMethods = property_exists($isGranted, 'methods') ? $isGranted->methods : [];
            if ([] !== $httpMethods && !\in_array($requestMethod, $httpMethods, true)) {
                continue;
            }

            // subjects are resolved from the arguments of the action, which this action doesn't
            // have, so the attributes that define one can't be checked and access is denied
            if (null === $isGranted->subject && $this->isGranted($isGranted->attribute)) {
                continue;
            }

            $message = $isGranted->message ?? 'Access Denied.';
            if (null !== $isGranted->statusCode) {
                throw new HttpException($isGranted->statusCode, $message, code: $isGranted->exceptionCode ?? 0);
            }

            $accessDeniedException = $this->createAccessDeniedException($message);
            $accessDeniedException->setAttributes([$isGranted->attribute]);

            throw $accessDeniedException;
        }
    }

    /**
     * @return iterable<WidgetInterface|WidgetSection>
     */
    public function configureWidgets(): iterable
    {
        return [];
    }

    public function configureDashboard(): Dashboard
    {
        return Dashboard::new();
    }

    public function configureAssets(): Assets
    {
        return Assets::new();
    }

    public function configureMenuItems(): iterable
    {
        yield MenuItem::linkToDashboard(t('page_title.dashboard', domain: 'EasyAdminBundle'), 'internal:home');
    }

    public function configureUserMenu(UserInterface $user): UserMenu
    {
        $userMenuItems = [];

        $userMenuItems[] = MenuItem::section();
        $userMenuItems[] = MenuItem::linkToLogout(t('user.sign_out', domain: 'EasyAdminBundle'), 'internal:sign-out');
        if ($this->isGranted(Permission::EA_EXIT_IMPERSONATION)) {
            $userMenuItems[] = MenuItem::linkToExitImpersonation(t('user.exit_impersonation', domain: 'EasyAdminBundle'), 'internal:user-lock');
        }

        $userName = $user instanceof \Stringable ? (string) $user : $user->getUserIdentifier();

        return UserMenu::new()
            ->displayUserName()
            ->displayUserAvatar()
            ->setName($userName)
            ->setAvatarUrl(null)
            ->setMenuItems($userMenuItems);
    }

    public function configureCrud(): Crud
    {
        return Crud::new();
    }

    public function configureActions(): Actions
    {
        return Actions::new()
            ->addBatchAction(Action::BATCH_DELETE)
            ->add(Crud::PAGE_INDEX, Action::NEW)
            ->add(Crud::PAGE_INDEX, Action::EDIT)
            ->add(Crud::PAGE_INDEX, Action::DELETE)

            ->add(Crud::PAGE_DETAIL, Action::EDIT)
            ->add(Crud::PAGE_DETAIL, Action::INDEX)
            ->add(Crud::PAGE_DETAIL, Action::DELETE)

            ->add(Crud::PAGE_EDIT, Action::SAVE_AND_RETURN)
            ->add(Crud::PAGE_EDIT, Action::SAVE_AND_CONTINUE)

            ->add(Crud::PAGE_NEW, Action::SAVE_AND_RETURN)
            ->add(Crud::PAGE_NEW, Action::SAVE_AND_ADD_ANOTHER)
        ;
    }

    public function configureFilters(): Filters
    {
        return Filters::new();
    }
}
