<?php

namespace EasyCorp\Bundle\EasyAdminBundle\Maker;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping\ClassMetadata;
use EasyCorp\Bundle\EasyAdminBundle\Contracts\Field\FieldInterface;
use EasyCorp\Bundle\EasyAdminBundle\Field\ArrayField;
use EasyCorp\Bundle\EasyAdminBundle\Field\AssociationField;
use EasyCorp\Bundle\EasyAdminBundle\Field\BooleanField;
use EasyCorp\Bundle\EasyAdminBundle\Field\ChoiceField;
use EasyCorp\Bundle\EasyAdminBundle\Field\DateField;
use EasyCorp\Bundle\EasyAdminBundle\Field\DateTimeField;
use EasyCorp\Bundle\EasyAdminBundle\Field\EmailField;
use EasyCorp\Bundle\EasyAdminBundle\Field\IdField;
use EasyCorp\Bundle\EasyAdminBundle\Field\IntegerField;
use EasyCorp\Bundle\EasyAdminBundle\Field\NumberField;
use EasyCorp\Bundle\EasyAdminBundle\Field\TelephoneField;
use EasyCorp\Bundle\EasyAdminBundle\Field\TextareaField;
use EasyCorp\Bundle\EasyAdminBundle\Field\TextField;
use EasyCorp\Bundle\EasyAdminBundle\Field\TimeField;
use EasyCorp\Bundle\EasyAdminBundle\Field\UrlField;
use Symfony\Bridge\Doctrine\Types\UlidType;
use Symfony\Bridge\Doctrine\Types\UuidType;

/**
 * Guesses the fields of the CRUD controllers generated by the make:admin:crud
 * command from the Doctrine metadata of their entities.
 *
 * It doesn't reuse the guessing done by FieldFactory at runtime because the
 * generated code is meant to be a starting point that users edit, so it also
 * considers enums, property names and on which pages each field is displayed.
 *
 * @author Javier Eguiluz <javier.eguiluz@gmail.com>
 *
 * @internal
 */
final readonly class CrudFieldGuesser
{
    // same limit as the default fields displayed on the index page (see FieldProvider)
    private const MAX_INDEX_COLUMNS = 7;

    /**
     * Fields such as SlugField, ImageField or MoneyField are never guessed
     * because they need some config option that this guesser can't know.
     *
     * @var array<string, class-string<FieldInterface>>
     */
    private const FIELD_FQCN_BY_DOCTRINE_TYPE = [
        // don't use Types::ARRAY and Types::OBJECT (removed in Doctrine DBAL 4) or Types::SIMPLE_ARRAY (deprecated in DBAL 4)
        'array' => ArrayField::class,
        'object' => TextField::class,
        'simple_array' => ArrayField::class,
        Types::ASCII_STRING => TextField::class,
        Types::BIGINT => IntegerField::class,
        Types::BINARY => TextareaField::class,
        Types::BLOB => TextareaField::class,
        Types::BOOLEAN => BooleanField::class,
        Types::DATE_MUTABLE => DateField::class,
        Types::DATE_IMMUTABLE => DateField::class,
        Types::DATEINTERVAL => TextField::class,
        Types::DATETIME_MUTABLE => DateTimeField::class,
        Types::DATETIME_IMMUTABLE => DateTimeField::class,
        Types::DATETIMETZ_MUTABLE => DateTimeField::class,
        Types::DATETIMETZ_IMMUTABLE => DateTimeField::class,
        Types::DECIMAL => NumberField::class,
        Types::FLOAT => NumberField::class,
        Types::GUID => TextField::class,
        Types::INTEGER => IntegerField::class,
        Types::JSON => ArrayField::class,
        Types::SMALLINT => IntegerField::class,
        Types::STRING => TextField::class,
        Types::TEXT => TextareaField::class,
        Types::TIME_MUTABLE => TimeField::class,
        Types::TIME_IMMUTABLE => TimeField::class,
        UlidType::NAME => TextField::class,
        UuidType::NAME => TextField::class,
    ];

    // these values are generated by the application or the database, or they are not editable as text
    private const TYPES_HIDDEN_ON_FORMS = [Types::DATEINTERVAL, Types::GUID, 'object', UlidType::NAME, UuidType::NAME];

    // binary contents aren't readable as text, so they are not suggested and only displayed on the detail page
    private const TYPES_ONLY_ON_DETAIL = [Types::BINARY, Types::BLOB];

    private const TYPES_NOT_SUGGESTED = [Types::BINARY, Types::BLOB, Types::DATEINTERVAL, 'object'];

    // these values are too long or too complex to be displayed in a table column
    private const TYPES_HIDDEN_ON_INDEX = ['array', Types::BINARY, Types::BLOB, Types::GUID, Types::JSON, 'object', 'simple_array', Types::TEXT, UlidType::NAME, UuidType::NAME];

    // same properties excluded from the index page by FieldProvider
    private const PROPERTIES_HIDDEN_ON_INDEX = ['password', 'salt', 'slug', 'updatedAt', 'uuid'];

    private const SECRET_PROPERTIES = ['password', 'salt'];

    private const TIMESTAMP_PROPERTIES = ['createdAt', 'updatedAt'];

    private const DATE_AND_TIME_TYPES = [
        Types::DATE_MUTABLE, Types::DATE_IMMUTABLE,
        Types::DATETIME_MUTABLE, Types::DATETIME_IMMUTABLE,
        Types::DATETIMETZ_MUTABLE, Types::DATETIMETZ_IMMUTABLE,
        Types::TIME_MUTABLE, Types::TIME_IMMUTABLE,
    ];

    /**
     * Returns the fields of all the properties with a supported Doctrine type,
     * sorted in the same order as the properties are declared in the entity.
     *
     * @param ClassMetadata<object> $metadata
     *
     * @return array<string, GuessedField> the fields indexed by property name
     */
    public function guess(ClassMetadata $metadata): array
    {
        $fields = [];
        foreach ($this->getPropertyNamesInDeclarationOrder($metadata) as $propertyName) {
            $field = $metadata->hasAssociation($propertyName)
                ? $this->guessAssociationField($metadata, $propertyName)
                : $this->guessPropertyField($metadata, $propertyName);

            if (null !== $field) {
                $fields[$propertyName] = $field;
            }
        }

        return $fields;
    }

    /**
     * Keeps on the index page only the first fields that are displayed there,
     * so the index page shows a few columns and the other pages show all fields.
     *
     * @param list<GuessedField> $fields
     *
     * @return list<GuessedField>
     */
    public function limitIndexColumns(array $fields): array
    {
        $numIndexColumns = 0;

        return array_map(static function (GuessedField $field) use (&$numIndexColumns): GuessedField {
            if (!$field->isDisplayedOnIndex()) {
                return $field;
            }

            return ++$numIndexColumns > self::MAX_INDEX_COLUMNS ? $field->hideOnIndex() : $field;
        }, $fields);
    }

    /**
     * @param ClassMetadata<object> $metadata
     */
    private function guessAssociationField(ClassMetadata $metadata, string $propertyName): GuessedField
    {
        $field = new GuessedField($propertyName, AssociationField::class);

        return $metadata->isCollectionValuedAssociation($propertyName) ? $field->hideOnIndex() : $field;
    }

    /**
     * @param ClassMetadata<object> $metadata
     */
    private function guessPropertyField(ClassMetadata $metadata, string $propertyName): ?GuessedField
    {
        // In Doctrine ORM 2.x, getFieldMapping() returns an array; in Doctrine ORM 3.x, it's a FieldMapping object
        $fieldMapping = $metadata->getFieldMapping($propertyName);
        /** @phpstan-ignore-next-line function.impossibleType */
        if (\is_array($fieldMapping)) {
            /** @phpstan-ignore-next-line cast.useless */
            $fieldMapping = (object) $fieldMapping;
        }
        $type = $fieldMapping->type;
        $enumType = $fieldMapping->enumType ?? null;

        if (!$metadata->isIdentifierComposite && $metadata->isIdentifier($propertyName)) {
            return new GuessedField($propertyName, IdField::class, ['->hideOnForm()']);
        }

        if (\in_array($propertyName, self::SECRET_PROPERTIES, true)) {
            return new GuessedField($propertyName, TextField::class, ['->onlyOnForms()'], suggested: false);
        }

        // ChoiceField gets its choices from the enum when no choices are configured;
        // Doctrine stores lists of enums in array columns, which need multiple choices
        if (null !== $enumType) {
            $calls = \in_array($type, [Types::JSON, 'simple_array'], true) ? ['->allowMultipleChoices()'] : [];

            return new GuessedField($propertyName, ChoiceField::class, $calls);
        }

        $fieldFqcn = (Types::STRING === $type ? $this->guessFieldFqcnFromPropertyName($propertyName) : null)
            ?? self::FIELD_FQCN_BY_DOCTRINE_TYPE[$type]
            ?? null;
        if (null === $fieldFqcn) {
            return null;
        }

        $calls = match (true) {
            \in_array($type, self::TYPES_ONLY_ON_DETAIL, true) => ['->onlyOnDetail()'],
            \in_array($type, self::TYPES_HIDDEN_ON_FORMS, true) => ['->hideOnForm()'],
            \in_array($type, self::DATE_AND_TIME_TYPES, true) && \in_array($propertyName, self::TIMESTAMP_PROPERTIES, true) => ['->hideOnForm()'],
            default => [],
        };
        $field = new GuessedField($propertyName, $fieldFqcn, $calls, !\in_array($type, self::TYPES_NOT_SUGGESTED, true));

        if (\in_array($type, self::TYPES_HIDDEN_ON_INDEX, true) || \in_array($propertyName, self::PROPERTIES_HIDDEN_ON_INDEX, true)) {
            return $field->hideOnIndex();
        }

        return $field;
    }

    /**
     * @return class-string<FieldInterface>|null
     */
    private function guessFieldFqcnFromPropertyName(string $propertyName): ?string
    {
        $propertyName = strtolower($propertyName);

        return match (true) {
            str_contains($propertyName, 'email') => EmailField::class,
            str_contains($propertyName, 'url'), str_contains($propertyName, 'website') => UrlField::class,
            str_contains($propertyName, 'phone') => TelephoneField::class,
            default => null,
        };
    }

    /**
     * Sorts the mapped properties as they are declared in the entity class,
     * starting with the properties of its parent classes. The sub-fields of
     * embedded properties (e.g. 'price.amount') are placed where the embedded
     * property is declared.
     *
     * @param ClassMetadata<object> $metadata
     *
     * @return list<string>
     */
    private function getPropertyNamesInDeclarationOrder(ClassMetadata $metadata): array
    {
        $classHierarchy = [];
        for ($class = new \ReflectionClass($metadata->getName()); false !== $class; $class = $class->getParentClass()) {
            array_unshift($classHierarchy, $class);
        }

        // properties are read class by class because getProperties() doesn't return the private properties of parent classes
        $declaredPropertyNames = [];
        foreach ($classHierarchy as $class) {
            foreach ($class->getProperties() as $property) {
                if ($property->getDeclaringClass()->getName() === $class->getName()) {
                    $declaredPropertyNames[] = $property->getName();
                }
            }
        }
        $declarationPositions = array_flip(array_unique($declaredPropertyNames));

        $getPosition = static function (string $propertyName) use ($declarationPositions): int {
            $declaredPropertyName = explode('.', $propertyName, 2)[0];

            return $declarationPositions[$declaredPropertyName] ?? \PHP_INT_MAX;
        };

        $propertyNames = [...$metadata->getFieldNames(), ...$metadata->getAssociationNames()];
        usort($propertyNames, static fn (string $a, string $b): int => $getPosition($a) <=> $getPosition($b));

        return $propertyNames;
    }
}
